#!/bin/bash
# Install (or remove) the XP25-AI reverse tunnel service on the home KVM host.
# Run as root:
#   sudo bash remote-access/home/install-home.sh --record RECORD.json \
#        --key TUNNEL_PRIVATE_KEY --aws-credentials CREDENTIALS_FILE [--local-port 5925]
#   sudo bash remote-access/home/install-home.sh --uninstall
#
# RECORD.json is provision_relay.py's record (relay instance, private address,
# port and pinned host key). The key and credentials files are copied into
# /etc/xp25-tunnel (readable only by the xp25-tunnel account); delete your
# staging copies afterwards. Nothing secret is printed.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
plugin_version=1.2.896.0
plugin_sha256=53f51fcc67314a4bf85888a38a3967cd41f8d0f28a60a9469a63acf935ba713e
plugin_url=https://s3.amazonaws.com/session-manager-downloads/plugin/$plugin_version/ubuntu_64bit/session-manager-plugin.deb

[[ $EUID -eq 0 ]] || { echo 'run as root (sudo)' >&2; exit 1; }
record= key= creds= local_port=5925 uninstall=0
while [[ $# -gt 0 ]]; do
  case $1 in
    --record) record=$2; shift 2 ;;
    --key) key=$2; shift 2 ;;
    --aws-credentials) creds=$2; shift 2 ;;
    --local-port) local_port=$2; shift 2 ;;
    --uninstall) uninstall=1; shift ;;
    *) echo "unknown argument $1" >&2; exit 2 ;;
  esac
done

if [[ $uninstall == 1 ]]; then
  systemctl disable --now xp25-tunnel.service 2>/dev/null || true
  rm -f /etc/systemd/system/xp25-tunnel.service
  systemctl daemon-reload
  rm -rf /usr/local/lib/xp25-tunnel /etc/xp25-tunnel /var/lib/xp25-tunnel
  id xp25-tunnel >/dev/null 2>&1 && userdel xp25-tunnel
  echo 'xp25-tunnel removed (session-manager-plugin package left installed)'
  exit 0
fi

for f in "$record" "$key" "$creds"; do [[ -f $f ]] || { echo "missing file: '$f'" >&2; exit 2; }; done
[[ $local_port =~ ^[0-9]+$ ]] || { echo 'bad --local-port' >&2; exit 2; }
read -r instance private_ip relay_port host_key < <(/usr/bin/python3 - "$record" <<'EOF'
import json, re, sys
r = json.load(open(sys.argv[1]))
assert re.fullmatch(r'i-[0-9a-f]{8,17}', r['instance_id'])
assert re.fullmatch(r'\d+\.\d+\.\d+\.\d+', r['private_ip'])
assert re.fullmatch(r'ssh-ed25519 [A-Za-z0-9+/=]+', r['host_key'])
print(r['instance_id'], r['private_ip'], int(r['vnc_port']), r['host_key'])
EOF
)
grep -q '^\[default\]' "$creds" || { echo 'credentials file needs a [default] profile' >&2; exit 2; }
ssh-keygen -y -f "$key" >/dev/null || { echo 'unreadable private key' >&2; exit 2; }

# 1. AWS Session Manager plugin, pinned by version and SHA-256.
if [[ $(/usr/local/sessionmanagerplugin/bin/session-manager-plugin --version 2>/dev/null) != "$plugin_version" ]]; then
  tmp=$(mktemp -d)
  curl -fsSL -o "$tmp/smp.deb" "$plugin_url"
  echo "$plugin_sha256  $tmp/smp.deb" | sha256sum -c --quiet -
  dpkg -i "$tmp/smp.deb" >/dev/null
  rm -rf "$tmp"
fi

# 2. Dedicated unprivileged account and files.
id xp25-tunnel >/dev/null 2>&1 || useradd --system --user-group --home-dir /var/lib/xp25-tunnel --shell /usr/sbin/nologin xp25-tunnel
install -d -m 0700 -o xp25-tunnel -g xp25-tunnel /var/lib/xp25-tunnel
install -d -m 0750 -o root -g xp25-tunnel /etc/xp25-tunnel
install -m 0600 -o xp25-tunnel -g xp25-tunnel "$key" /etc/xp25-tunnel/id_ed25519
install -m 0600 -o xp25-tunnel -g xp25-tunnel "$creds" /etc/xp25-tunnel/aws-credentials
echo "xp25-relay $host_key" > /etc/xp25-tunnel/known_hosts
cat > /etc/xp25-tunnel/ssh_config <<EOF
# Generated by install-home.sh. The relay is reached through SSM Session
# Manager; it has no inbound SSH rule and sshd there listens on loopback only.
Host xp25-relay
    HostName $instance
    User xp25tunnel
    IdentityFile /etc/xp25-tunnel/id_ed25519
    IdentitiesOnly yes
    UserKnownHostsFile /etc/xp25-tunnel/known_hosts
    GlobalKnownHostsFile /dev/null
    HostKeyAlias xp25-relay
    StrictHostKeyChecking yes
    UpdateHostKeys no
    ProxyCommand /usr/local/lib/xp25-tunnel/xp25-ssm-proxy %h
    BatchMode yes
    SessionType none
    RequestTTY no
    ControlMaster no
    ForwardAgent no
    ForwardX11 no
    PermitLocalCommand no
    ExitOnForwardFailure yes
    ServerAliveInterval 30
    ServerAliveCountMax 3
    ConnectTimeout 45
    LogLevel VERBOSE
    RemoteForward $private_ip:$relay_port 127.0.0.1:$local_port
EOF
cat > /etc/xp25-tunnel/README <<EOF
xp25-tunnel: SSH reverse tunnel from this host's XP25-AI VNC console
(127.0.0.1:$local_port) to the relay $instance ($private_ip:$relay_port), carried
over AWS SSM Session Manager. Guacamole's guacd connects to the relay address.
  systemctl status xp25-tunnel        journalctl -u xp25-tunnel -f
  systemctl restart xp25-tunnel       systemctl stop xp25-tunnel
Files: id_ed25519 and aws-credentials (xp25-tunnel only), known_hosts (pinned
relay host key), ssh_config. Installed from the winxp_2026 repository's
remote-access/home directory.
EOF
chmod 0644 /etc/xp25-tunnel/known_hosts /etc/xp25-tunnel/ssh_config /etc/xp25-tunnel/README
install -d -m 0755 /usr/local/lib/xp25-tunnel
install -m 0755 "$here/xp25-ssm-proxy" "$here/xp25-tunnel-health" /usr/local/lib/xp25-tunnel/
install -m 0644 "$here/xp25-tunnel.service" /etc/systemd/system/xp25-tunnel.service

# 3. Start now and at every boot.
systemctl daemon-reload
systemctl enable xp25-tunnel.service >/dev/null
systemctl restart xp25-tunnel.service
sleep 20
systemctl --no-pager --lines=0 status xp25-tunnel.service || true
journalctl -u xp25-tunnel.service -n 8 --no-pager -o cat
