#!/usr/bin/env python3
"""Prepare native NT build media for MerlinAI: only the XP25 MerlinAI sources
(components/merlin and the portable SHA-256 from components/xp25-agent/llm),
generated resources and the build driver, as an ISO for the private build VM.
The reference tree under Source/ is not copied or modified.

usage: prepare_merlin.py --output .work/<fresh> [--source <tree>]
  --source  build from another checkout of the repository (a MerlinAI Builder
            job workspace); defaults to this repository."""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build'))
import merlin_build


def make_tree(source, out, media):
    """The MerlinAI build tree media/merlin from the repository at source; returns the generated wrappers."""
    tree = media / 'merlin'
    shutil.copytree(source / 'components/merlin', tree / 'merlin',
                    ignore=shutil.ignore_patterns('__pycache__', '*.pyc', 'builder', 'host', '*.ini'))
    (tree / 'xp25-agent/llm').mkdir(parents=True)
    for name in ('xp25_sha256.c', 'xp25_sha256.h'):
        shutil.copy2(source / 'components/xp25-agent/llm' / name, tree / 'xp25-agent/llm' / name)
    (tree / 'dirs').write_bytes(b'DIRS=merlin\r\n')
    res = out / 'res'
    merlin_build.resources(res)
    for directory in ('client', 'crash', 'app', 'cpl'):
        for name in ('merlin.ico', 'merlinmsg.bin', 'merlin.manifest'):
            shutil.copy2(res / name, tree / 'merlin' / directory / name)
    wrappers = {}
    for sources in tree.rglob('sources'):
        text = sources.read_text()

        def local(match):
            path = match.group(0)
            name = 'x_' + path.replace('\\', '/').split('/')[-1]
            (sources.parent / name).write_text('/* Generated by build/prepare_merlin.py: compiles ' + path +
                                               ' in place so its own relative includes resolve. */\n#include "' +
                                               path.replace('\\', '/') + '"\n')
            wrappers[str((sources.parent / name).relative_to(tree))] = path
            return name
        sources.write_text(re.sub(r'(?:\.\.\\)+[\w\\.-]+\.c', local, text))
    for f in tree.rglob('*'):
        if f.is_file() and (f.suffix.lower() in ('.c', '.h', '.rc', '.def', '.manifest') or f.name in ('sources', 'dirs', 'makefile')):
            f.write_bytes(f.read_bytes().replace(b'\r\n', b'\n').replace(b'\n', b'\r\n'))
    return wrappers


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--source', type=Path, default=ROOT)
    args = parser.parse_args()
    out, source = args.output.resolve(), args.source.resolve()
    if not out.is_relative_to(ROOT / '.work') and not out.is_relative_to(source):
        parser.error('private .work/ output required')
    if (source / 'Source').exists() and out.is_relative_to(source / 'Source'):
        parser.error('output inside Source/ refused')
    out.mkdir(parents=True, exist_ok=False)
    media = out / 'media'
    wrappers = make_tree(source, out, media)
    (media / 'build.cmd').write_bytes((ROOT / 'build/native-merlin-build.cmd').read_bytes().replace(b'\r\n', b'\n').replace(b'\n', b'\r\n'))
    iso = out / 'native-merlin.iso'
    command = ['xorriso', '-as', 'mkisofs', '-quiet', '-iso-level', '3', '-J', '-R', '-V', 'XP25MERLIN', '-o', str(iso), str(media)]
    subprocess.run(command, check=True)
    files = {str(f.relative_to(media)): hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted(media.rglob('*')) if f.is_file()}
    git = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    dirty = subprocess.run(['git', '-C', str(source), 'status', '--porcelain', '--', 'components/merlin', 'components/xp25-agent/llm'],
                           capture_output=True, text=True)
    (out / 'manifest.json').write_text(json.dumps({'command': command, 'iso_sha256': hashlib.sha256(iso.read_bytes()).hexdigest(),
                                                   'source': str(source), 'source_commit': git.stdout.strip() or None,
                                                   'source_uncommitted_changes': dirty.stdout.splitlines(),
                                                   'files': files, 'wrappers': wrappers,
                                                   'scope': 'XP25 MerlinAI sources only; Source/ unchanged.'}, indent=2) + '\n')
    print(iso)


if __name__ == '__main__':
    main()
