#!/usr/bin/env python3
"""Generate or verify the XP25 pwrp_k32 proxy export table.

Every named export of the hash-pinned Supermium pwrp_k32.dll keeps its name
and ordinal. Each forwards to the renamed original, pwrp_k32_sm.dll, except
the thread-agnostic ReadDirectoryChangesW in components/browser/xp25_pwrp.c.
Original forwarders keep their original target. No browser code is executed.
"""
import argparse
import hashlib
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build'))
from inspect_component import PE

ORIGINAL_SHA256 = 'bbd3fc4880c9dee4472e951a82d767b99e0d82dc9fef2e27e225b16dd7b5fca8'
RENAMED = 'pwrp_k32_sm'
DEF = ROOT / 'components/browser/pwrp_k32.def'
IMPLEMENTED = {'ReadDirectoryChangesW': 'Xp25ReadDirectoryChangesW'}


def named_exports(path):
    pe = PE(path)
    rva, size = pe.directory(0)
    at = pe.offset(rva)
    base, count, named, functions, names, ordinals = struct.unpack_from('<IIIIII', pe.data, at + 16)
    rows = []
    for i in range(named):
        name = pe.string(pe.u32(pe.offset(names + i * 4)))
        index = pe.u16(pe.offset(ordinals + i * 2))
        value = pe.u32(pe.offset(functions + index * 4))
        rows.append((base + index, name, pe.string(value) if rva <= value < rva + size else None))
    live = sum(1 for i in range(count) if pe.u32(pe.offset(functions + i * 4)))
    if live != len({row[0] for row in rows}):
        raise ValueError('original has unnamed exports; a by-name proxy cannot reproduce them')
    return sorted(rows)


def proxy_def(original):
    digest = hashlib.sha256(Path(original).read_bytes()).hexdigest()
    if digest != ORIGINAL_SHA256:
        raise ValueError('pwrp_k32.dll does not match the pinned Supermium wrapper: ' + digest)
    rows = named_exports(original)
    if not IMPLEMENTED.keys() <= {name for _, name, _ in rows}:
        raise ValueError('implemented export missing from the original')
    lines = ['; Generated by build/pwrp_proxy.py from Supermium pwrp_k32.dll',
             '; SHA-256 ' + ORIGINAL_SHA256 + '. Do not edit.',
             'LIBRARY pwrp_k32', 'EXPORTS']
    for ordinal, name, forwarder in rows:
        target = IMPLEMENTED.get(name) or forwarder or RENAMED + '.' + name
        lines.append('    %s=%s @%d' % (name, target, ordinal))
    return '\r\n'.join(lines) + '\r\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--original', type=Path, required=True)
    p.add_argument('--check', action='store_true', help='verify the committed definition instead of writing it')
    a = p.parse_args()
    text = proxy_def(a.original)
    if a.check:
        if DEF.read_bytes() != text.encode('ascii'):
            raise SystemExit('components/browser/pwrp_k32.def does not match the pinned original')
        print('pwrp_k32.def matches', ORIGINAL_SHA256)
    else:
        DEF.write_bytes(text.encode('ascii'))
        print(DEF, len(text.splitlines()) - 4, 'exports')


if __name__ == '__main__':
    main()
