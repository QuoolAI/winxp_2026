#!/usr/bin/env python3
"""Prepare native NT build media for the XP25 AI components: only the
XP25 sources (components/xp25-agent, clippyai, roverai), generated icons and
the build driver, as an ISO for the private build VM. The reference tree
under Source/ is not copied or modified."""
import argparse
import hashlib
import json
import re
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'build'))
from ai_build import icons


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    out = args.output.resolve()
    if not out.is_relative_to(ROOT / '.work'):
        parser.error('private .work/ output required')
    out.mkdir(parents=True, exist_ok=False)
    media = out / 'media'
    tree = media / 'ai'
    for name in ('xp25-agent', 'clippyai', 'roverai'):
        shutil.copytree(ROOT / 'components' / name, tree / name, ignore=shutil.ignore_patterns('__pycache__', '*.pyc'))
    (tree / 'dirs').write_bytes(b'DIRS=xp25-agent clippyai roverai\r\n')
    wrappers = {}
    for sources in tree.rglob('sources'):
        text = sources.read_text()
        def local(match):
            path = match.group(0)
            name = 'x_' + path.replace('\\', '/').split('/')[-1]
            (sources.parent / name).write_text('/* Generated by build/prepare_ai.py: compiles ' + path +
                                               ' in place so its own relative includes resolve. */\n#include "' +
                                               path.replace('\\', '/') + '"\n')
            wrappers[str((sources.parent / name).relative_to(tree))] = path
            return name
        sources.write_text(re.sub(r'(?:\.\.\\)+[\w\\.-]+\.c', local, text))
    art = out / 'icons'
    icons(art)
    shutil.copy2(art / 'clippyai.ico', tree / 'clippyai/app/clippyai.ico')
    shutil.copy2(art / 'roverai.ico', tree / 'roverai/app/roverai.ico')
    shutil.copy2(art / 'roverai.ico', tree / 'roverai/explorer/roverai.ico')
    for f in tree.rglob('*'):
        if f.is_file() and f.suffix.lower() in ('.c', '.h', '.rc', '.def', '.manifest') or f.name in ('sources', 'dirs'):
            data = f.read_bytes().replace(b'\r\n', b'\n').replace(b'\n', b'\r\n')
            f.write_bytes(data)
    (media / 'build.cmd').write_bytes((ROOT / 'build/native-ai-build.cmd').read_bytes().replace(b'\r\n', b'\n').replace(b'\n', b'\r\n'))
    iso = out / 'native-ai.iso'
    command = ['xorriso', '-as', 'mkisofs', '-quiet', '-iso-level', '3', '-J', '-R', '-V', 'XP25AI', '-o', str(iso), str(media)]
    subprocess.run(command, check=True)
    files = {str(f.relative_to(media)): hashlib.sha256(f.read_bytes()).hexdigest() for f in sorted(media.rglob('*')) if f.is_file()}
    (out / 'manifest.json').write_text(json.dumps({'command': command, 'iso_sha256': hashlib.sha256(iso.read_bytes()).hexdigest(),
                                                   'files': files, 'wrappers': wrappers,
                                                   'scope': 'XP25 AI sources only; Source/ unchanged.'},
                                                  indent=2) + '\n')
    print(iso)


if __name__ == '__main__':
    main()
